#AgentState is the shared memory or data container of your LangGraph workflow. It allows different nodes to communicate and pass information to one another without directly calling each other.

# TypedDict: Defines the structure and expected types of a dictionary.
from typing import TypedDict, List, Annotated

# operator: Provides built-in operations such as addition.
import operator


# AgentState defines the shared state (memory/context)
# that flows between different nodes in our LangGraph agent.
class AgentState(TypedDict):

    # Conversation history.
    # Annotated + operator.add tells LangGraph to APPEND new messages
    # to existing messages instead of replacing the entire list.
    messages: Annotated[List[dict], operator.add]

    # Stores the user's current question or request.
    current_query: str

    # Stores document chunks retrieved from Qdrant
    # and potentially refined by the reranker.
    documents: List[str]

    # Stores the steps or actions the agent plans to execute.
    plan: List[str]

    # Tracks the current execution status of the agent.
    # Example: "planning", "retrieving", "completed", "failed".
    status: str

    # Stores the final response generated by the agent.
    final_answer: str