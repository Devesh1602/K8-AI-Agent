#The Retrieve Node is the knowledge-gathering component of your RAG agent. Qdrant finds 15 possible matches quickly, FlashRank carefully reorders them, and the five strongest candidates are passed to the Generator to produce a grounded answer.
import logfire

# Import the shared LangGraph state.
# This allows the retrieval node to read and update agent information.
from app.agents.state import AgentState

# Import the Qdrant semantic search function.
# It converts the query into an embedding and retrieves similar document chunks.
from app.services.retrieval.qdrant_service import search_enterprise_knowledge

# Import the FlashRank reranking function.
# It re-evaluates retrieved documents against the original query.
from app.services.retrieval.ranking_service import rerank_documents


def retrieve_node(state: AgentState):
    """
    Retrieval Node:
    Performs two-stage retrieval:
    1. Vector search using Qdrant.
    2. Semantic reranking using FlashRank.
    """

    # STEP 1: GET THE SEARCH QUERY
    # Read the refined query generated by the Planner node.
    query = state["current_query"]

    # STEP 2: INITIAL RETRIEVAL FROM QDRANT
    # Create a Logfire span to monitor the retrieval operation.
    with logfire.span("🔍 Knowledge Retrieval"):

        # Log the query being searched.
        logfire.info(f"Searching Qdrant for: {query}")

        # Convert the query into an embedding and search Qdrant.
        # Retrieve the top 15 semantically similar document chunks.
        #
        # These are candidate documents, not necessarily the
        # 15 most relevant answers.
        raw_results = search_enterprise_knowledge(
            query,
            limit=15
        )

        # Log how many candidates Qdrant returned.
        logfire.info(
            f"Retrieved {len(raw_results)} candidates from Vector DB"
        )

        # STEP 3: EXTRACT DOCUMENT CONTENT
        # Qdrant returns dictionaries containing content, source and score.
        # Extract only the document text for reranking.
        doc_contents = [
            doc["content"] for doc in raw_results
        ]

        # STEP 4: SEMANTIC RERANKING
        # Create a separate Logfire span to monitor reranking.
        with logfire.span("⚖️ Semantic Reranking"):

            # Pass the original query and 15 candidate documents
            # to FlashRank's Cross-Encoder model.
            #
            # FlashRank evaluates each query-document pair
            # and sorts documents by relevance.
            #
            # Keep only the top 5 documents after reranking.
            reranked_contents = rerank_documents(
                query,
                doc_contents,
                top_n=5
            )

            # Log completion of reranking.
            logfire.info(
                "Reranking complete. Kept top 5 most relevant chunks."
            )

        # STEP 5: FORMAT DOCUMENTS
        # Add a CONTENT prefix to each document chunk.
        # This makes the context easier to identify in the next node.
        formatted_docs = [
            f"CONTENT: {doc}" for doc in reranked_contents
        ]

    # STEP 6: UPDATE LANGGRAPH STATE
    # Return only the fields this node wants to update.
    return {

        # Save the top 5 reranked document chunks.
        # The Generator node will use these as technical context.
        "documents": formatted_docs,

        # Update the current workflow status.
        "status": "Found technical context.",

        # Append retrieval completion to the existing execution plan.
        "plan": state["plan"] + ["Context Retrieved"]
    }